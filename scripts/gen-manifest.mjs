// Generates src/lib/modules.generated.ts from the frontmatter of every
// `.svx` module. This decouples nav/search metadata from the compiled module
// bodies, so the sidebar (imported in the layout) never bundles lesson code and
// each module stays in its own lazily-loaded chunk.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const contentDir = join(root, 'src/lib/content');
const outFile = join(root, 'src/lib/modules.generated.ts');

function walk(dir) {
	const out = [];
	for (const name of readdirSync(dir)) {
		const full = join(dir, name);
		if (statSync(full).isDirectory()) out.push(...walk(full));
		else if (name.endsWith('.svx')) out.push(full);
	}
	return out;
}

function parseFrontmatter(text) {
	const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
	if (!m) return null;
	const meta = {};
	for (const raw of m[1].split(/\r?\n/)) {
		const line = raw.trim();
		if (!line || line.startsWith('#')) continue;
		const idx = line.indexOf(':');
		if (idx === -1) continue;
		const key = line.slice(0, idx).trim();
		let val = line.slice(idx + 1).trim();
		if (val.startsWith('[') && val.endsWith(']')) {
			meta[key] = val
				.slice(1, -1)
				.split(',')
				.map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
				.filter(Boolean);
		} else if (/^-?\d+(\.\d+)?$/.test(val)) {
			meta[key] = Number(val);
		} else {
			meta[key] = val.replace(/^['"]|['"]$/g, '');
		}
	}
	return meta;
}

const files = walk(contentDir);
const modules = [];
for (const file of files) {
	const meta = parseFrontmatter(readFileSync(file, 'utf8'));
	if (!meta || typeof meta.level !== 'number') continue;
	const slug = relative(contentDir, file).replace(/\\/g, '/').replace(/\.svx$/, '');
	modules.push({ slug, ...meta });
}

modules.sort((a, b) => a.level - b.level || a.order - b.order || a.slug.localeCompare(b.slug));

const banner = `// AUTO-GENERATED by scripts/gen-manifest.mjs — do not edit by hand.\n// Run \`node scripts/gen-manifest.mjs\` (also runs on predev/prebuild).\n`;
const body = `import type { ModuleMeta } from './content';\n\nexport const generatedModules: ModuleMeta[] = ${JSON.stringify(
	modules,
	null,
	'\t'
)};\n`;

writeFileSync(outFile, banner + '\n' + body);
console.log(`[gen-manifest] wrote ${modules.length} modules → ${relative(root, outFile)}`);
